-- =============================================================================
-- V4 · Operación del momento: grupos, entregas y evaluaciones (Etapa 1, D3)
-- Ver docs/03-entidades-dominio.md (Operations, Evaluation) y ADR-012.
-- Depende de V1 (moment, evaluation_criterion, performance_level) y de V3
-- (app_user, teacher, student, external_evaluator: herencia JOINED, ADR-009).
--
-- Política de borrado (propuesta, pendiente de confirmar con el equipo):
--   * Lo que es parte del grupo se borra con él: miembros, evaluadores asignados,
--     entregas, evaluaciones y sus calificaciones (ON DELETE CASCADE).
--   * Lo que es historial académico NO se borra en cascada desde afuera: un
--     momento, docente, criterio o nivel con grupos o notas no se puede borrar
--     (sin ON DELETE = RESTRICT). Así un borrado de configuración nunca se lleva
--     calificaciones de semestres pasados (ADR-010).
-- =============================================================================

CREATE TABLE project_group (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moment_id           BIGINT       NOT NULL,
    teacher_id          BIGINT       NOT NULL,
    name                VARCHAR(100) NOT NULL,
    project_title       VARCHAR(200),
    submission_deadline DATE,
    evaluation_date     DATE,
    CONSTRAINT uk_project_group_moment_teacher_name UNIQUE (moment_id, teacher_id, name),
    CONSTRAINT fk_project_group_moment FOREIGN KEY (moment_id)
        REFERENCES moment (id),
    CONSTRAINT fk_project_group_teacher FOREIGN KEY (teacher_id)
        REFERENCES teacher (id)
);

CREATE INDEX ix_project_group_teacher ON project_group (teacher_id);

-- Agregación grupo—estudiante. "Un grupo por momento" lo valida el service con
-- ProjectGroupRepository.existsByMomentIdAndMembersId (la tabla no tiene moment_id).
CREATE TABLE project_group_member (
    project_group_id BIGINT NOT NULL,
    student_id       BIGINT NOT NULL,
    CONSTRAINT pk_project_group_member PRIMARY KEY (project_group_id, student_id),
    CONSTRAINT fk_project_group_member_group FOREIGN KEY (project_group_id)
        REFERENCES project_group (id) ON DELETE CASCADE,
    CONSTRAINT fk_project_group_member_student FOREIGN KEY (student_id)
        REFERENCES student (id)
);

CREATE INDEX ix_project_group_member_student ON project_group_member (student_id);

CREATE TABLE project_group_evaluator (
    project_group_id      BIGINT NOT NULL,
    external_evaluator_id BIGINT NOT NULL,
    CONSTRAINT pk_project_group_evaluator PRIMARY KEY (project_group_id, external_evaluator_id),
    CONSTRAINT fk_project_group_evaluator_group FOREIGN KEY (project_group_id)
        REFERENCES project_group (id) ON DELETE CASCADE,
    CONSTRAINT fk_project_group_evaluator_evaluator FOREIGN KEY (external_evaluator_id)
        REFERENCES external_evaluator (id)
);

CREATE INDEX ix_project_group_evaluator_evaluator ON project_group_evaluator (external_evaluator_id);

-- La restricción única evita dos versiones con el mismo número si dos
-- integrantes suben a la vez.
CREATE TABLE submission (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_group_id  BIGINT       NOT NULL,
    version_number    INTEGER      NOT NULL,
    zip_file_path     VARCHAR(500) NOT NULL,
    presentation_path VARCHAR(500) NOT NULL,
    submitted_at      TIMESTAMP    NOT NULL,
    CONSTRAINT uk_submission_group_version UNIQUE (project_group_id, version_number),
    CONSTRAINT fk_submission_group FOREIGN KEY (project_group_id)
        REFERENCES project_group (id) ON DELETE CASCADE,
    CONSTRAINT ck_submission_version_positive CHECK (version_number > 0)
);

-- evaluator_id apunta a app_user porque el evaluador puede ser un docente o un
-- evaluador externo (dos tablas distintas en la herencia JOINED).
CREATE TABLE evaluation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_group_id BIGINT    NOT NULL,
    evaluator_id     BIGINT    NOT NULL,
    evaluated_at     TIMESTAMP NOT NULL,
    CONSTRAINT uk_evaluation_group_evaluator UNIQUE (project_group_id, evaluator_id),
    CONSTRAINT fk_evaluation_group FOREIGN KEY (project_group_id)
        REFERENCES project_group (id) ON DELETE CASCADE,
    CONSTRAINT fk_evaluation_evaluator FOREIGN KEY (evaluator_id)
        REFERENCES app_user (id)
);

CREATE INDEX ix_evaluation_evaluator ON evaluation (evaluator_id);

CREATE TABLE criterion_grade (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id        BIGINT        NOT NULL,
    criterion_id         BIGINT        NOT NULL,
    performance_level_id BIGINT        NOT NULL,
    score                NUMERIC(5, 2) NOT NULL,
    CONSTRAINT uk_criterion_grade_evaluation_criterion UNIQUE (evaluation_id, criterion_id),
    CONSTRAINT fk_criterion_grade_evaluation FOREIGN KEY (evaluation_id)
        REFERENCES evaluation (id) ON DELETE CASCADE,
    CONSTRAINT fk_criterion_grade_criterion FOREIGN KEY (criterion_id)
        REFERENCES evaluation_criterion (id),
    CONSTRAINT fk_criterion_grade_level FOREIGN KEY (performance_level_id)
        REFERENCES performance_level (id),
    CONSTRAINT ck_criterion_grade_score CHECK (score >= 0)
);

CREATE INDEX ix_criterion_grade_criterion ON criterion_grade (criterion_id);
CREATE INDEX ix_criterion_grade_level ON criterion_grade (performance_level_id);
