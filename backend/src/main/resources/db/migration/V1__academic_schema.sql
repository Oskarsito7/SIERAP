-- =============================================================================
-- V1 · Academic structure and assessment configuration (Stage 1, D2)
-- See docs/03-entidades-dominio.md, ADR-010 (configuration per period) and
-- ADR-012 (moment lifecycle).
-- Composition: faculty -> program -> moment -> learning_outcome ->
-- evaluation_criterion -> performance_level (ON DELETE CASCADE).
-- Association: moment -> academic_period.
-- =============================================================================

CREATE TABLE faculty (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL
);

CREATE TABLE program (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(20)  NOT NULL,
    name       VARCHAR(150) NOT NULL,
    faculty_id BIGINT       NOT NULL,
    CONSTRAINT uk_program_code UNIQUE (code),
    CONSTRAINT fk_program_faculty FOREIGN KEY (faculty_id)
        REFERENCES faculty (id) ON DELETE CASCADE
);

CREATE TABLE academic_period (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    VARCHAR(20) NOT NULL,
    start_date              DATE        NOT NULL,
    end_date                DATE        NOT NULL,
    upc_evaluation_deadline DATE        NOT NULL,
    CONSTRAINT uk_academic_period_code UNIQUE (code)
);

-- key/value are reserved words in SQL, hence param_key/param_value.
CREATE TABLE global_parameter (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    param_key   VARCHAR(100) NOT NULL,
    param_value VARCHAR(500) NOT NULL,
    description VARCHAR(500),
    CONSTRAINT uk_global_parameter_key UNIQUE (param_key)
);

-- The date windows may be empty while the moment is being configured; they are
-- required to launch it (validated in the service, ADR-012).
CREATE TABLE moment (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id            BIGINT       NOT NULL,
    period_id             BIGINT       NOT NULL,
    number                INTEGER      NOT NULL,
    name                  VARCHAR(100) NOT NULL,
    subject               VARCHAR(150) NOT NULL,
    semester_from         INTEGER      NOT NULL,
    semester_to           INTEGER      NOT NULL,
    requirement_level     VARCHAR(100) NOT NULL,
    min_members           INTEGER      NOT NULL,
    max_members           INTEGER      NOT NULL,
    status                VARCHAR(20)  NOT NULL,
    group_formation_start DATE,
    group_formation_end   DATE,
    submission_start      DATE,
    submission_end        DATE,
    grading_start         DATE,
    grading_end           DATE,
    CONSTRAINT uk_moment_program_period_number UNIQUE (program_id, period_id, number),
    CONSTRAINT fk_moment_program FOREIGN KEY (program_id)
        REFERENCES program (id) ON DELETE CASCADE,
    CONSTRAINT fk_moment_period FOREIGN KEY (period_id)
        REFERENCES academic_period (id),
    CONSTRAINT ck_moment_status CHECK (status IN ('CONFIGURATION', 'LAUNCHED'))
);

CREATE INDEX ix_moment_period ON moment (period_id);

CREATE TABLE learning_outcome (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moment_id   BIGINT        NOT NULL,
    code        VARCHAR(20)   NOT NULL,
    description VARCHAR(1000) NOT NULL,
    CONSTRAINT uk_learning_outcome_moment_code UNIQUE (moment_id, code),
    CONSTRAINT fk_learning_outcome_moment FOREIGN KEY (moment_id)
        REFERENCES moment (id) ON DELETE CASCADE
);

CREATE TABLE evaluation_criterion (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learning_outcome_id BIGINT       NOT NULL,
    description         VARCHAR(500) NOT NULL,
    display_order       INTEGER      NOT NULL,
    CONSTRAINT fk_evaluation_criterion_learning_outcome FOREIGN KEY (learning_outcome_id)
        REFERENCES learning_outcome (id) ON DELETE CASCADE
);

CREATE INDEX ix_evaluation_criterion_learning_outcome ON evaluation_criterion (learning_outcome_id);

CREATE TABLE performance_level (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criterion_id  BIGINT        NOT NULL,
    name          VARCHAR(50)   NOT NULL,
    description   VARCHAR(1000),
    score         NUMERIC(5, 2) NOT NULL,
    display_order INTEGER       NOT NULL,
    CONSTRAINT fk_performance_level_criterion FOREIGN KEY (criterion_id)
        REFERENCES evaluation_criterion (id) ON DELETE CASCADE
);

CREATE INDEX ix_performance_level_criterion ON performance_level (criterion_id);
