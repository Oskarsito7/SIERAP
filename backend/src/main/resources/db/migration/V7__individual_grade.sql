-- Etapa 6 (ADR-018): el grupo se califica una vez y cada evaluador puede ajustar el
-- nivel de algunos criterios para un estudiante. Cada ajuste guarda una copia del
-- puntaje del nivel (como criterion_grade) y hay como máximo uno por estudiante y
-- criterio en cada evaluación. Va después de V8 en el tiempo, pero conserva el número
-- reservado; en dev aplica gracias a flyway.out-of-order.

CREATE TABLE individual_grade (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id        BIGINT        NOT NULL,
    student_id           BIGINT        NOT NULL,
    criterion_id         BIGINT        NOT NULL,
    performance_level_id BIGINT        NOT NULL,
    score                NUMERIC(5, 2) NOT NULL,
    CONSTRAINT uk_individual_grade_evaluation_student_criterion
        UNIQUE (evaluation_id, student_id, criterion_id),
    CONSTRAINT fk_individual_grade_evaluation FOREIGN KEY (evaluation_id)
        REFERENCES evaluation (id) ON DELETE CASCADE,
    CONSTRAINT fk_individual_grade_student FOREIGN KEY (student_id)
        REFERENCES student (id),
    CONSTRAINT fk_individual_grade_criterion FOREIGN KEY (criterion_id)
        REFERENCES evaluation_criterion (id),
    CONSTRAINT fk_individual_grade_level FOREIGN KEY (performance_level_id)
        REFERENCES performance_level (id),
    CONSTRAINT ck_individual_grade_score CHECK (score >= 0)
);

CREATE INDEX ix_individual_grade_student ON individual_grade (student_id);
CREATE INDEX ix_individual_grade_criterion ON individual_grade (criterion_id);
CREATE INDEX ix_individual_grade_level ON individual_grade (performance_level_id);
