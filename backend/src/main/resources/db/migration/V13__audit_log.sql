-- =============================================================================
-- V13 · Bitácora de auditoría inmutable (ADR-023)
-- Registra quién hizo qué y cuándo en las operaciones sensibles (cuentas, códigos,
-- momentos, parámetros, evaluaciones y grupos). Solo se inserta: un trigger impide
-- UPDATE y DELETE, de modo que ni la aplicación ni un acceso directo puedan alterar
-- la historia. actor_name es una copia del nombre al momento del hecho; faculty_id no
-- tiene llave foránea para que la historia sobreviva a cualquier cambio del catálogo.
-- =============================================================================

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP     NOT NULL,
    actor_id    BIGINT,
    actor_name  VARCHAR(250),
    action      VARCHAR(50)   NOT NULL,
    entity_type VARCHAR(50)   NOT NULL,
    entity_id   BIGINT,
    faculty_id  BIGINT,
    summary     VARCHAR(1000) NOT NULL,
    ip          VARCHAR(64),
    CONSTRAINT fk_audit_log_actor FOREIGN KEY (actor_id) REFERENCES app_user (id)
);

CREATE INDEX idx_audit_log_created_at ON audit_log (created_at DESC);
CREATE INDEX idx_audit_log_faculty_id ON audit_log (faculty_id);

CREATE FUNCTION audit_log_reject_change() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'La bitácora de auditoría es inmutable: no admite % sobre audit_log', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_log_immutable
    BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION audit_log_reject_change();
