-- Las cuentas creadas por otro usuario no tienen contraseña hasta que la persona
-- usa el enlace enviado por correo.
ALTER TABLE app_user ALTER COLUMN password_hash DROP NOT NULL;

-- Contraseña temporal que debe cambiarse en el primer ingreso (primer super_admin).
ALTER TABLE app_user ADD COLUMN must_change_password BOOLEAN NOT NULL DEFAULT FALSE;

-- Quién creó la cuenta (o el docente dueño del código con el que se registró el
-- estudiante). Los usuarios no se borran, se desactivan; SET NULL es solo por si acaso.
ALTER TABLE app_user ADD COLUMN created_by_id BIGINT;
ALTER TABLE app_user ADD CONSTRAINT fk_app_user_created_by
    FOREIGN KEY (created_by_id) REFERENCES app_user (id) ON DELETE SET NULL;
CREATE INDEX ix_app_user_created_by ON app_user (created_by_id);

-- Códigos que el docente comparte para que sus estudiantes se registren solos.
CREATE TABLE registration_code (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(20) NOT NULL,
    teacher_id BIGINT      NOT NULL,
    program_id BIGINT      NOT NULL,
    expires_on DATE        NOT NULL,
    active     BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP   NOT NULL,
    CONSTRAINT uk_registration_code_code UNIQUE (code),
    CONSTRAINT fk_registration_code_teacher FOREIGN KEY (teacher_id) REFERENCES teacher (id),
    CONSTRAINT fk_registration_code_program FOREIGN KEY (program_id) REFERENCES program (id)
);

CREATE INDEX ix_registration_code_teacher ON registration_code (teacher_id);

ALTER TABLE student ADD COLUMN registration_code_id BIGINT;
ALTER TABLE student ADD CONSTRAINT fk_student_registration_code
    FOREIGN KEY (registration_code_id) REFERENCES registration_code (id);
CREATE INDEX ix_student_registration_code ON student (registration_code_id);

-- Sesiones: solo se guarda el hash SHA-256 del valor que viaja en la cookie.
-- rotated_at marca el token que ya se cambió por uno nuevo; si vuelve a llegar, es
-- señal de robo. Cerrar sesión o cambiar la contraseña borra las filas.
CREATE TABLE refresh_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP   NOT NULL,
    rotated_at TIMESTAMP,
    created_at TIMESTAMP   NOT NULL,
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);

CREATE INDEX ix_refresh_token_user ON refresh_token (user_id);

-- Enlaces de un solo uso para crear o recuperar la contraseña.
CREATE TABLE password_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    purpose    VARCHAR(20) NOT NULL,
    expires_at TIMESTAMP   NOT NULL,
    used_at    TIMESTAMP,
    created_at TIMESTAMP   NOT NULL,
    CONSTRAINT uk_password_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_password_token_purpose CHECK (purpose IN ('ACCOUNT_SETUP', 'PASSWORD_RESET')),
    CONSTRAINT fk_password_token_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);

CREATE INDEX ix_password_token_user ON password_token (user_id);

