-- Ver docs/03-entidades-dominio.md, ADR-009 (herencia JOINED), ADR-011 (tipos de
-- evaluador configurables) y ADR-016 (política de borrado).
-- Herencia JOINED: app_user guarda los datos comunes y cada rol tiene su tabla con
-- la misma llave primaria (ON DELETE CASCADE hacia app_user).
-- Los usuarios nunca se borran en cascada desde la configuración: las llaves hacia
-- faculty, program y evaluator_type son RESTRICT.
-- =============================================================================

-- Catálogo de tipos de evaluador externo que mantiene el super_admin (ADR-011).
CREATE TABLE evaluator_type (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_evaluator_type_name UNIQUE (name)
);

-- "user" es palabra reservada en PostgreSQL, por eso app_user (ADR-014).
CREATE TABLE app_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role            VARCHAR(30)  NOT NULL,
    first_names     VARCHAR(100) NOT NULL,
    last_names      VARCHAR(100) NOT NULL,
    document_type   VARCHAR(20)  NOT NULL,
    document_number VARCHAR(30)  NOT NULL,
    email           VARCHAR(150) NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP    NOT NULL,
    CONSTRAINT uk_app_user_document_number UNIQUE (document_number),
    CONSTRAINT ck_app_user_role
        CHECK (role IN ('SUPER_ADMIN', 'ADMIN', 'TEACHER', 'STUDENT', 'EXTERNAL_EVALUATOR')),
    CONSTRAINT ck_app_user_document_type CHECK (document_type IN ('CC', 'TI', 'CE', 'PASSPORT')),
    CONSTRAINT ck_app_user_email_normalized CHECK (email = LOWER(TRIM(email)))
);

-- El correo se guarda normalizado (la entidad lo pasa a minúsculas); el índice
-- sobre LOWER protege además contra inserciones directas con mayúsculas.
CREATE UNIQUE INDEX uk_app_user_email ON app_user (LOWER(email));

CREATE TABLE super_admin (
    id BIGINT PRIMARY KEY,
    CONSTRAINT fk_super_admin_user FOREIGN KEY (id) REFERENCES app_user (id) ON DELETE CASCADE
);

-- Una facultad puede tener varios admins (decisión del 2026-09-25).
CREATE TABLE admin (
    id         BIGINT PRIMARY KEY,
    faculty_id BIGINT NOT NULL,
    CONSTRAINT fk_admin_user FOREIGN KEY (id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_admin_faculty FOREIGN KEY (faculty_id) REFERENCES faculty (id)
);

CREATE INDEX ix_admin_faculty ON admin (faculty_id);

CREATE TABLE teacher (
    id         BIGINT PRIMARY KEY,
    faculty_id BIGINT NOT NULL,
    CONSTRAINT fk_teacher_user FOREIGN KEY (id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_teacher_faculty FOREIGN KEY (faculty_id) REFERENCES faculty (id)
);

CREATE INDEX ix_teacher_faculty ON teacher (faculty_id);

CREATE TABLE student (
    id               BIGINT PRIMARY KEY,
    student_code     VARCHAR(30) NOT NULL,
    current_semester INTEGER     NOT NULL,
    program_id       BIGINT      NOT NULL,
    CONSTRAINT uk_student_code UNIQUE (student_code),
    CONSTRAINT ck_student_current_semester CHECK (current_semester >= 1),
    CONSTRAINT fk_student_user FOREIGN KEY (id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_student_program FOREIGN KEY (program_id) REFERENCES program (id)
);

CREATE INDEX ix_student_program ON student (program_id);

-- "position" es palabra reservada del estándar SQL, por eso job_position (ADR-014).
CREATE TABLE external_evaluator (
    id                    BIGINT PRIMARY KEY,
    evaluator_type_id     BIGINT       NOT NULL,
    organization          VARCHAR(150),
    job_position          VARCHAR(100),
    graduation_year       INTEGER,
    graduation_program_id BIGINT,
    CONSTRAINT ck_external_evaluator_graduation_year
        CHECK (graduation_year IS NULL OR graduation_year BETWEEN 1900 AND 2100),
    CONSTRAINT fk_external_evaluator_user FOREIGN KEY (id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_external_evaluator_type FOREIGN KEY (evaluator_type_id) REFERENCES evaluator_type (id),
    CONSTRAINT fk_external_evaluator_program FOREIGN KEY (graduation_program_id) REFERENCES program (id)
);

CREATE INDEX ix_external_evaluator_type ON external_evaluator (evaluator_type_id);

