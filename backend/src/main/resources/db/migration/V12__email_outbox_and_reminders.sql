-- =============================================================================
-- V12 · Cola de correos (outbox transaccional) y recordatorios por fecha — ADR-022
-- =============================================================================

-- Correos pendientes de envío. Se escribe una fila dentro de la transacción de la
-- operación que lo pide (si hace rollback, el correo desaparece); un despachador
-- programado los envía por SMTP con reintentos y espera exponencial.
CREATE TABLE email_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient       VARCHAR(255)  NOT NULL,
    subject         VARCHAR(255)  NOT NULL,
    body            TEXT          NOT NULL,
    status          VARCHAR(10)   NOT NULL DEFAULT 'PENDING',
    attempts        INTEGER       NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP     NOT NULL,
    last_error      VARCHAR(1000),
    created_at      TIMESTAMP     NOT NULL,
    sent_at         TIMESTAMP,
    CONSTRAINT ck_email_outbox_status CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT ck_email_outbox_attempts CHECK (attempts >= 0)
);

CREATE INDEX ix_email_outbox_status_next_attempt ON email_outbox (status, next_attempt_at);

-- Recordatorios ya encolados: evita repetirlos si el trabajo corre dos veces o el
-- servidor se reinicia. reference_id es el grupo (cierre de entregas, evaluación
-- pendiente) o el momento (notas publicadas); recipient_id es el usuario avisado.
CREATE TABLE reminder_sent (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         VARCHAR(30) NOT NULL,
    reference_id BIGINT      NOT NULL,
    recipient_id BIGINT      NOT NULL,
    sent_on      DATE        NOT NULL,
    CONSTRAINT ck_reminder_sent_kind CHECK (kind IN ('SUBMISSION_CLOSING', 'EVALUATION_PENDING', 'GRADES_PUBLISHED')),
    CONSTRAINT uk_reminder_sent UNIQUE (kind, reference_id, recipient_id),
    CONSTRAINT fk_reminder_sent_recipient FOREIGN KEY (recipient_id) REFERENCES app_user (id) ON DELETE CASCADE
);
