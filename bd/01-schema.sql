-- =============================================================================
-- V9 · Pesos por tipo de evaluador en el momento (Etapa 3, D2)
-- La nota final es un promedio ponderado por tipo de evaluador (ADR-018): el
-- docente y cada EvaluatorType tienen un peso en el momento, en porcentaje.
--
-- El peso del docente es una columna del momento porque todo momento tiene
-- docente; el de cada tipo de evaluador externo es una fila de evaluator_weight,
-- compuesta por el momento. Un tipo sin fila no tiene peso en el momento y no se
-- pueden designar evaluadores de ese tipo.
--
-- La regla de que los pesos sumen 100 compara varias filas y la valida
-- Moment.launch(). Los momentos que ya existen quedan con el docente al 100 %.
-- =============================================================================

ALTER TABLE moment
    ADD COLUMN teacher_weight NUMERIC(5, 2) NOT NULL DEFAULT 100,
    ADD CONSTRAINT ck_moment_teacher_weight
        CHECK (teacher_weight > 0 AND teacher_weight <= 100);

