    CONSTRAINT fk_evaluator_weight_moment FOREIGN KEY (moment_id)
        REFERENCES moment (id) ON DELETE CASCADE,
    CONSTRAINT fk_evaluator_weight_type FOREIGN KEY (evaluator_type_id)
        REFERENCES evaluator_type (id),
    CONSTRAINT ck_evaluator_weight_weight CHECK (weight > 0 AND weight <= 100)
